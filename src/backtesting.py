"""
Temporal backtesting framework for the WHEN target.

Step 1 (this file so far): inspect how snapshots spread across calendar
years, so the holdout boundary and the walk-forward cutoffs can be placed
with the real volume in view. Nothing is split or filtered here.

Usage:
    from backtesting import load_or_build_snapshots, year_distribution
    snapshots = load_or_build_snapshots()
    table = year_distribution(snapshots)
"""

from __future__ import annotations

from pathlib import Path  # path handling for the cache file

import matplotlib.pyplot as plt  # plotting library for the yearly bar chart
import pandas as pd  # dataframe library used throughout

import numpy as np  # array maths for the bootstrap
from sklearn.metrics import average_precision_score, classification_report, roc_auc_score  # PR-AUC, ROC-AUC and the per-class precision and recall

from baselines import KILL_GATE_CONFIDENCE, N_BOOTSTRAP, SEED  # same confidence level and resample count as the kill gate
from snapshots import CONFIG, ROOT, build_snapshots  # builds one row per snapshot from the Works table

# Where the cleaned Works table lives and where the built snapshots are cached.
WORKS_PATH = ROOT / CONFIG["paths"]["works"]  # paths.works
SNAPSHOTS_PATH = ROOT / CONFIG["paths"]["snapshots"]  # paths.snapshots

# The Discogs dump is dated 2026-09-01, so 2026 is only partly observed.
PARTIAL_YEAR = CONFIG["years"]["partial"]  # years.partial

# A complete year is "low volume" when its snapshot count is below this
# quantile of the yearly counts of all complete years.
LOW_VOLUME_QUANTILE = 0.10


def load_or_build_snapshots(works_path: Path = WORKS_PATH, snapshots_path: Path = SNAPSHOTS_PATH) -> pd.DataFrame:
    """Read the cached snapshots, or build them from the Works table and cache them."""
    if snapshots_path.exists():  # cache hit, skip the expensive rebuild
        return pd.read_parquet(snapshots_path)  # return the cached snapshots as they were saved
    works = pd.read_parquet(works_path)  # cleaned Works table, one row per Work
    snapshots = build_snapshots(works)  # one row per snapshot, with next_1y / next_2y targets
    snapshots.to_parquet(snapshots_path)  # cache so later runs do not rebuild 5M+ rows
    return snapshots  # hand back the freshly built snapshots


def year_distribution(snapshots: pd.DataFrame, low_quantile: float = LOW_VOLUME_QUANTILE, partial_year: int = PARTIAL_YEAR) -> pd.DataFrame:
    """Count snapshots per year and flag low-volume and partial years.

    The low-volume threshold is the `low_quantile` quantile of the yearly
    counts of complete years only, so the partial year never drags the
    threshold down and is never flagged as low volume. It gets its own
    `partial` flag instead.
    """
    counts = snapshots.groupby("year").size().rename("snapshots")  # snapshots generated by each year's works
    table = counts.to_frame()  # one row per year
    table["share"] = table["snapshots"] / table["snapshots"].sum()  # fraction of all snapshots in that year
    table["cum_share"] = table["share"].cumsum()  # chronological cumulative fraction, used to place the holdout
    table["partial"] = table.index == partial_year  # year not fully observed in the dump
    complete_counts = table.loc[~table["partial"], "snapshots"]  # counts of fully observed years only
    threshold = complete_counts.quantile(low_quantile)  # volume cut below which a year is low volume
    table["low_volume"] = (table["snapshots"] < threshold) & ~table["partial"]  # partial year is flagged apart
    table.attrs["low_volume_threshold"] = threshold  # keep the cut so the notebook can report it
    return table  # indexed by year


def plot_year_distribution(table: pd.DataFrame) -> None:
    """Bar chart of snapshots per year, low-volume and partial years in different colors."""
    colors = table.apply(lambda r: "tab:orange" if r["partial"] else ("tab:red" if r["low_volume"] else "tab:blue"), axis=1)  # color by flag
    fig, ax = plt.subplots(figsize=(14, 4))  # wide figure, one bar per year
    ax.bar(table.index, table["snapshots"], color=colors)  # snapshots per year
    ax.axhline(table.attrs["low_volume_threshold"], color="gray", linestyle="--", label="low-volume threshold (p10)")  # the cut
    ax.set_yscale("log")  # volumes span several orders of magnitude
    ax.set_xlabel("year")  # x axis label
    ax.set_ylabel("snapshots (log scale)")  # y axis label
    ax.set_title("Snapshots per year (red = low volume, orange = partial year)")  # legend for the colors
    ax.legend()  # show the threshold line label
    plt.show()  # render the figure


# Final holdout boundary: the chronologically most recent complete years that
# are not affected by Discogs submission lag (see docs/decisions.md).
HOLDOUT_START_YEAR = CONFIG["years"]["holdout_start"]  # years.holdout_start
HOLDOUT_END_YEAR = CONFIG["years"]["holdout_end"]  # years.holdout_end


def split_holdout(snapshots: pd.DataFrame, holdout_start: int = HOLDOUT_START_YEAR, holdout_end: int = HOLDOUT_END_YEAR, partial_year: int = PARTIAL_YEAR) -> dict:
    """Split snapshots by year into development, holdout, excluded_recent and demo.

    - development: years before `holdout_start`, used for walk-forward folds and tuning.
    - holdout: `holdout_start` to `holdout_end`, untouched until the final evaluation.
    - excluded_recent: complete years after `holdout_end`. Their counts are
      artificially low (Discogs submission lag), so they are used neither
      for training nor for the evaluation metric. Kept for demo use.
    - demo: the partial year (and anything after), kept for demo use only.
    """
    year = snapshots["year"]  # anchor year of each snapshot
    parts = {
        "development": snapshots[year < holdout_start],  # everything before the holdout window
        "holdout": snapshots[(year >= holdout_start) & (year <= holdout_end)],  # final evaluation window
        "excluded_recent": snapshots[(year > holdout_end) & (year < partial_year)],  # complete but lag-affected years
        "demo": snapshots[year >= partial_year],  # partial year, not fully observed
    }
    assert sum(len(p) for p in parts.values()) == len(snapshots)  # every snapshot lands in exactly one bucket
    return parts  # dict of the four dataframes


def split_summary(parts: dict) -> pd.DataFrame:
    """Rows, share of all snapshots, year range and artist count for each bucket."""
    total = sum(len(p) for p in parts.values())  # all snapshots across buckets
    rows = {
        name: {
            "snapshots": len(p),  # rows in the bucket
            "share": len(p) / total,  # fraction of all snapshots
            "first_year": p["year"].min(),  # earliest anchor year
            "last_year": p["year"].max(),  # latest anchor year
            "artists": p["artist_id"].nunique(),  # distinct artists with a snapshot in the bucket
        }
        for name, p in parts.items()
    }
    return pd.DataFrame(rows).T  # one row per bucket


# Longest label horizon (next_2y) in years. A train row whose year is within
# this many years of the start of a test or holdout period has a label that
# reaches into that period, so it is excluded from training (a gap, as in
# purged cross-validation for time series).
GAP_YEARS = CONFIG["years"]["label_gap"]  # years.label_gap

# Walk-forward test tranches: the last N_FOLD_TRANCHES * TRANCHE_YEARS
# development years are split into N_FOLD_TRANCHES consecutive tranches of
# TRANCHE_YEARS calendar years each (1993-1997 ... 2013-2017 for a holdout
# starting in 2018). Defaults of make_what_folds, same values as make_folds.
N_FOLD_TRANCHES = 5
TRANCHE_YEARS = 5


def holdout_gap(development: pd.DataFrame, holdout_start: int = HOLDOUT_START_YEAR, gap_years: int = GAP_YEARS) -> tuple:
    """Split development into rows safe to train the final model on and the gap rows.

    A development row with `year >= holdout_start - gap_years` has a
    next_1y / next_2y label that can look into the holdout years, so it is
    not used to train the model that gets evaluated on the holdout. These
    rows stay in `development` for the walk-forward test tranches.
    """
    in_gap = development["year"] >= holdout_start - gap_years  # label window can reach into the holdout
    return development[~in_gap], development[in_gap]  # (final_train, boundary_gap)


def make_folds(development: pd.DataFrame, n_folds: int = 5, test_years: int = 5, target: str = "next_1y", low_volume_years=(), gap_years: int = GAP_YEARS) -> list:
    """Expanding-window walk-forward folds cut by calendar year, with a gap before each test tranche.

    The last `n_folds * test_years` calendar years of `development` are split
    into `n_folds` consecutive test tranches of `test_years` calendar years
    each. Fold k trains on every year before its tranche minus the gap and
    tests on the tranche, so each tranche moves from test to train in the
    next fold. Tranche volumes are whatever the calendar years produce.

    Two exclusions are applied per fold:
    - gap: train rows with `year >= test_start - gap_years` are dropped,
      because their next_1y / next_2y labels reach into the test tranche;
    - censoring: test rows whose `target` is NaN (not resolved with real
      data) are dropped.
    An artist may have rows on both sides of a fold, that is not leakage
    (features are point-in-time safe and train labels are gapped).

    Returns one dict per fold with `train`, `test` and the counts needed to
    judge how much each rule removed.
    """
    last_year = development["year"].max()  # last development year, end of the final tranche
    first_test_year = last_year - n_folds * test_years + 1  # first year of fold 1's test tranche
    folds = []  # one dict per fold
    for k in range(n_folds):  # fold 1 tests the earliest tranche
        start = first_test_year + k * test_years  # first test year of this fold
        end = start + test_years - 1  # last test year of this fold
        if set(range(start, end + 1)) & set(low_volume_years):  # a tranche must not sit in a low-volume zone
            raise ValueError(f"fold {k + 1} test tranche {start}-{end} overlaps a low-volume year")
        before = development[development["year"] < start]  # everything before the tranche
        train = before[before["year"] < start - gap_years]  # expanding window minus the gap
        test_all = development[(development["year"] >= start) & (development["year"] <= end)]  # calendar tranche
        test = test_all[test_all[target].notna()]  # censoring: keep only resolved targets
        folds.append({
            "fold": k + 1,  # 1-based fold number
            "train_years": f"{train['year'].min()}-{start - gap_years - 1}",  # train window after the gap
            "gap_years": f"{start - gap_years}-{start - 1}",  # years removed from train
            "test_years": f"{start}-{end}",  # test tranche
            "gap_rows": len(before) - len(train),  # train rows removed by the gap
            "train_rows": len(train),  # rows available for training
            "test_rows_raw": len(test_all),  # rows in the tranche before censoring
            "censored_rows": len(test_all) - len(test),  # rows removed because the target is unresolved
            "test_rows": len(test),  # final test rows
            "test_artists": test["artist_id"].nunique(),  # artists in the final test set
            "test_artists_in_train": int(test["artist_id"].isin(set(train["artist_id"])).sum()),  # test rows by artists that also have train rows
            "history_median": test["history_count"].median(),  # typical prior works of the test rows
            "train": train,  # train dataframe
            "test": test,  # test dataframe
        })
    return folds  # list of fold dicts


def fold_summary(folds: list) -> pd.DataFrame:
    """One row per fold with the counts of make_folds, without the dataframes."""
    table = pd.DataFrame([{k: v for k, v in f.items() if k not in ("train", "test")} for f in folds]).set_index("fold")  # drop dataframes
    table = table.rename(columns={"test_artists_in_train": "test_rows_with_train_artist"})  # it counts rows, not artists
    table["share_with_train_artist"] = table["test_rows_with_train_artist"] / table["test_rows"]  # share of test rows by artists seen in train
    return table  # one row per fold


def make_what_folds(table: pd.DataFrame, n_folds: int = N_FOLD_TRANCHES, test_years: int = TRANCHE_YEARS, holdout_start: int = HOLDOUT_START_YEAR) -> list:
    """Expanding-window walk-forward folds for WHAT, cut by calendar year, with a label-resolution rule instead of a gap.

    `table` is the output of `build_what_table` (labelled artist-year rows
    only). Only development years (`year` < `holdout_start`) are used, so the
    holdout is never read. The last `n_folds * test_years` calendar years of
    development are split into `n_folds` consecutive test tranches of
    `test_years` calendar years each, exactly as in `make_folds`. Fold k
    trains on every year before its tranche and tests on the tranche.

    One exclusion is applied per fold:
    - resolution rule: train rows with `next_active_year >= test_start` are
      dropped, because the label of an artist-year is only known once its next
      active year has happened, and that can be more than 2 years later, so the
      fixed gap of `make_folds` would not close the leak.
    There is no censoring, every row of `table` already has a label.
    An artist may have rows on both sides of a fold, that is not leakage
    (features are point-in-time safe and train labels are resolved).

    Returns one dict per fold with the keys of `make_folds`, so `fold_summary`
    and `evaluate_folds` work unchanged (`gap_years` is the text "resolution
    rule", `gap_rows` counts the rows removed by the rule, `test_rows_raw`
    equals `test_rows` and `censored_rows` is 0), plus `dropped_by_resolution_rule`
    and `test_rows_label_beyond_tranche` (test rows whose `next_active_year` is
    after the tranche end, informational, same as the WHEN test labels).
    """
    development = table[table["year"] < holdout_start]  # development years only, the holdout is never read
    last_year = development["year"].max()  # last development year, end of the final tranche
    first_test_year = last_year - n_folds * test_years + 1  # first year of fold 1's test tranche
    folds = []  # one dict per fold
    for k in range(n_folds):  # fold 1 tests the earliest tranche
        start = first_test_year + k * test_years  # first test year of this fold
        end = start + test_years - 1  # last test year of this fold
        before = development[development["year"] < start]  # everything before the tranche
        train = before[before["next_active_year"] < start]  # expanding window, only labels resolved before the test starts
        test = development[(development["year"] >= start) & (development["year"] <= end)]  # calendar tranche, all rows labelled
        dropped = len(before) - len(train)  # train rows removed by the resolution rule
        folds.append({
            "fold": k + 1,  # 1-based fold number
            "train_years": f"{train['year'].min()}-{train['year'].max()}",  # train window after the rule
            "gap_years": "resolution rule",  # no fixed gap, the rule replaces it
            "test_years": f"{start}-{end}",  # test tranche
            "gap_rows": dropped,  # train rows removed by the rule
            "train_rows": len(train),  # rows available for training
            "test_rows_raw": len(test),  # rows in the tranche, nothing is censored
            "censored_rows": 0,  # the table has labelled rows only
            "test_rows": len(test),  # final test rows
            "test_artists": test["artist_id"].nunique(),  # artists in the final test set
            "test_artists_in_train": int(test["artist_id"].isin(set(train["artist_id"])).sum()),  # test rows by artists that also have train rows
            "history_median": test["history_count"].median(),  # typical prior works of the test rows
            "train": train,  # train dataframe
            "test": test,  # test dataframe
            "dropped_by_resolution_rule": dropped,  # same number as gap_rows, named for what it is
            "test_rows_label_beyond_tranche": int((test["next_active_year"] > end).sum()),  # test labels that look past the tranche end
        })
    return folds  # list of fold dicts


def point_in_time_check(works: pd.DataFrame, cutoff_year: int, n_artists: int = 30000, seed: int = SEED) -> pd.Series:
    """Count, per snapshot column, the rows whose value changes when the future is removed.

    Builds the snapshots twice for a random sample of artists: once from all
    their Works and once from only the Works dated up to `cutoff_year`
    (undated Works are kept, they have no year to cut on). Then compares both
    builds on the snapshots with `year <= cutoff_year`. A column that only
    uses information up to the snapshot's own year must be identical in both
    (0 rows differ); a column that differs looks into later years.
    """
    artists = works["artist_id"].dropna().drop_duplicates().sample(n_artists, random_state=seed)  # random artist sample
    sample = works[works["artist_id"].isin(artists)]  # all Works of the sampled artists
    truncated = sample[sample["year"].isna() | (sample["year"] <= cutoff_year)]  # the same Works without the future
    full = build_snapshots(sample).set_index("work_id")  # snapshots built with the future available
    cut = build_snapshots(truncated).set_index("work_id")  # snapshots built without it
    full = full[full["year"] <= cutoff_year]  # compare only snapshots inside the truncated window
    cut = cut.loc[full.index]  # same rows, same order
    differs = {}  # rows that change, per column
    for col in full.columns:  # every snapshot column
        same = (full[col] == cut[col]) | (full[col].isna() & cut[col].isna())  # equal, counting NaN == NaN
        differs[col] = int((~same).sum())  # rows whose value changed
    return pd.Series(differs)  # 0 means identical with and without the future


def presence_truncation_check(clean_fn, works: pd.DataFrame, cutoff_year: int, n_artists: int = 30000, n_big_artists: int = 10000, seed: int = SEED) -> dict:
    """Test whether a cleaning step lets later Works decide the fate of earlier ones.

    Applies `clean_fn` (a function Works -> Works that only removes rows)
    twice to a sample of artists: once to all their Works and once to only
    the Works dated up to `cutoff_year` (undated Works are kept). A dated
    Work with `year <= cutoff_year` must survive in both runs or in neither;
    if its survival changes, the step used information from later Works.
    The sample is `n_artists` random artists plus `n_big_artists` artists
    with 30 or more Works (large catalogs are where window effects show).
    """
    counts = works.groupby("artist_id").size()  # Works per artist
    random_artists = counts.sample(n_artists, random_state=seed).index  # random artists
    big_pool = counts[counts >= 30].index  # artists with large catalogs
    big_artists = big_pool.to_series().sample(min(n_big_artists, len(big_pool)), random_state=seed).values  # extra large-catalog artists
    sample = works[works["artist_id"].isin(set(random_artists) | set(big_artists))]  # all Works of the sampled artists
    truncated = sample[sample["year"].isna() | (sample["year"] <= cutoff_year)]  # the same Works without the future
    kept_full = set(clean_fn(sample)["work_id"])  # survivors when the future is available
    kept_cut = set(clean_fn(truncated)["work_id"])  # survivors when it is not
    dated = truncated[truncated["year"].notna()]["work_id"]  # dated Works inside the window
    undated = truncated[truncated["year"].isna()]["work_id"]  # undated Works, kept in both runs
    return {
        "dated_works": len(dated),  # dated Works compared
        "dated_changed": int(sum((w in kept_full) != (w in kept_cut) for w in dated)),  # survival differs with and without the future
        "undated_works": len(undated),  # undated Works compared
        "undated_changed": int(sum((w in kept_full) != (w in kept_cut) for w in undated)),  # same, for undated Works
    }


def mass_upload_truncation_check(works: pd.DataFrame, remove_fn, cutoff_years=(1990, 2000, 2010), min_work_count: int = 50) -> pd.DataFrame:
    """Compare which artists the mass-upload rule flags with and without later Works.

    The rule needs at least `min_work_count` Works, so only artists above
    that floor in the full catalog are run (the rest cannot be flagged at
    any cutoff). For each cutoff the Works dated after it are removed
    (undated Works are kept) and the flagged set is compared with the one
    from the full catalog.
    """
    counts = works.groupby("artist_id").size()  # Works per artist in the full catalog
    big = works[works["artist_id"].isin(counts[counts >= min_work_count].index)]  # artists that can be flagged at all
    flagged = lambda df: set(df["artist_id"]) - set(remove_fn(df)["artist_id"])  # artists the rule removes from df
    full = flagged(big)  # flagged with the whole catalog
    rows = []  # one row per cutoff
    for year in cutoff_years:
        truncated = big[big["year"].isna() | (big["year"] <= year)]  # the same Works without the future
        cut = flagged(truncated)  # flagged without the future
        rows.append({"cutoff": year, "flagged_full": len(full), "flagged_truncated": len(cut),
                     "only_truncated": len(cut - full), "only_full": len(full - cut)})  # disagreement in both directions
    return pd.DataFrame(rows).set_index("cutoff")  # one row per cutoff


def master_year_provenance(works: pd.DataFrame, masters: pd.DataFrame) -> pd.Series:
    """Where each master-side Work's final `year` comes from, against masters.parquet.

    `year == 0` in the masters table is a missing-year sentinel, so it counts
    as missing here. A year that differs from a present master year would
    mean some step rewrote it (an imputation that was not fully reverted).
    """
    master_works = works[works["work_source"] == "master"]  # synthetic Works have no master year to compare to
    master_year = masters.set_index("master_id")["year"].astype(float).replace(0, float("nan"))  # sentinel 0 counts as missing
    original = master_works["work_id"].map(master_year)  # the year Discogs holds for this master
    final = master_works["year"].astype(float)  # the year in the final Works table
    return pd.Series({
        "master_works": len(master_works),  # all master-side Works
        "same_as_masters_year": int((final == original).sum()),  # untouched
        "recovered_from_own_releases": int((original.isna() & final.notna()).sum()),  # filled by recover_missing_master_years
        "differs_from_present_master_year": int((original.notna() & (final != original)).sum()),  # would mean a stray imputation
        "still_missing": int((original.isna() & final.isna()).sum()),  # left as NaN
    })


def _weighted_average_precision(y_sorted: np.ndarray, weights: np.ndarray, group_ends: np.ndarray) -> float:
    """Average precision (the PR-AUC of sklearn) of rows already sorted by score, descending, with row weights.

    `group_ends` holds the last position of every block of tied scores, so
    ties are cut together as in sklearn's average_precision_score.
    """
    tp = np.cumsum(weights * y_sorted)[group_ends]  # weighted positives found up to each threshold
    seen = np.cumsum(weights)[group_ends]  # weighted rows seen up to each threshold
    if tp[-1] == 0 or tp[-1] == seen[-1]:  # one class only, PR-AUC undefined
        return np.nan
    precision = np.divide(tp, seen, out=np.zeros_like(tp), where=seen > 0)  # precision at each threshold, 0 where nothing weighted was seen yet
    recall = tp / tp[-1]  # recall at each threshold
    return float(np.sum(np.diff(recall, prepend=0.0) * precision))  # sum of recall steps times precision


def _artist_bootstrap_pr_auc(y_true: np.ndarray, scores: np.ndarray, artist_ids: np.ndarray, n_bootstrap: int, seed: int) -> np.ndarray:
    """Artist-clustered bootstrap of PR-AUC, same idea as baselines._bootstrap_pr_auc but fast.

    Resampling artists with replacement is the same as giving every row of
    an artist a weight equal to how many times the artist was drawn, so
    nothing is copied: the rows are sorted by score once and each draw only
    recomputes weighted cumulative sums. baselines._bootstrap_pr_auc builds
    a dict of row positions per artist with one full-array scan per artist
    (artists x rows operations), which does not finish at fold size.
    """
    rng = np.random.default_rng(seed)  # reproducible draws
    codes = pd.factorize(artist_ids)[0]  # artist id -> 0..n_artists-1
    n_artists = codes.max() + 1  # number of distinct artists
    order = np.argsort(-scores, kind="stable")  # rows by score, descending
    y_sorted = y_true[order].astype(float)  # labels in that order
    codes_sorted = codes[order]  # artist codes in that order
    s_sorted = scores[order]  # scores in that order
    group_ends = np.append(np.flatnonzero(s_sorted[1:] != s_sorted[:-1]), len(s_sorted) - 1)  # last row of each tie block
    pr_aucs = np.empty(n_bootstrap)  # one PR-AUC per draw
    for i in range(n_bootstrap):
        draws = np.bincount(rng.integers(0, n_artists, n_artists), minlength=n_artists)  # times each artist was drawn
        pr_aucs[i] = _weighted_average_precision(y_sorted, draws[codes_sorted].astype(float), group_ends)  # weights by artist
    return pr_aucs  # NaN where a draw had one class only


def evaluate_folds(folds: list, target: str, fit_fn, score_fn, n_bootstrap: int = N_BOOTSTRAP, confidence: float = KILL_GATE_CONFIDENCE, seed: int = SEED) -> pd.DataFrame:
    """Per-fold metrics for one fit/score pair, one row per fold, never averaged.

    `fit_fn(train)` returns the fitted object learned from the fold's train
    rows only, `score_fn(test, fitted)` returns one score per test row
    (higher = more likely `target` == 1). `folds` must come from make_folds
    with the same `target`, so every test row has a resolved label.
    """
    alpha = (1 - confidence) / 2  # two-sided tail, 0.025 each side at 95%
    rows = []  # one dict per fold
    for f in folds:
        train, test = f["train"], f["test"]  # fold dataframes
        assert test[target].notna().all()  # censoring already applied for this target
        scores = np.asarray(score_fn(test, fit_fn(train)))  # fit on train only, score test
        y = test[target].to_numpy()  # resolved labels
        boot = _artist_bootstrap_pr_auc(y, scores, test["artist_id"].to_numpy(), n_bootstrap, seed)  # PR-AUC draws
        rows.append({
            "fold": f["fold"],  # 1-based fold number
            "test_years": f["test_years"],  # test tranche
            "train_rows": len(train),  # rows the fit saw
            "test_rows": len(test),  # rows scored
            "positive_rate": y.mean(),  # PR-AUC of a no-skill score
            "pr_auc": _weighted_average_precision(*_sorted_inputs(y, scores)),  # point estimate on the full test set
            "pr_auc_lo": np.nanquantile(boot, alpha),  # lower bound of the artist-clustered CI
            "pr_auc_hi": np.nanquantile(boot, 1 - alpha),  # upper bound
            "roc_auc": roc_auc_score(y, scores),  # for reference
        })
    return pd.DataFrame(rows).set_index("fold")  # fold by fold, no average


def _sorted_inputs(y: np.ndarray, scores: np.ndarray) -> tuple:
    """Unit weights, labels sorted by score and tie-block ends, the inputs of _weighted_average_precision."""
    order = np.argsort(-scores, kind="stable")  # rows by score, descending
    s_sorted = scores[order]  # scores in that order
    group_ends = np.append(np.flatnonzero(s_sorted[1:] != s_sorted[:-1]), len(s_sorted) - 1)  # last row of each tie block
    return y[order].astype(float), np.ones(len(y)), group_ends  # (y_sorted, weights, group_ends)


def evaluate_holdout(final_train: pd.DataFrame, holdout: pd.DataFrame, target: str, fit_fn, score_fn, n_bootstrap: int = N_BOOTSTRAP, confidence: float = KILL_GATE_CONFIDENCE, seed: int = SEED, threshold: float = 0.5, return_scores: bool = False) -> dict:
    """The one-time final evaluation on the sealed holdout.

    Fits on `final_train` (development without the label gap), scores the
    holdout rows whose `target` is resolved, and reports PR-AUC and ROC-AUC
    with artist-clustered bootstrap intervals, the same metrics by holdout
    year, and precision and recall at `threshold` (sklearn's
    classification_report, as a dict). With `return_scores=True` the result
    also carries the holdout `scores` and `labels` (arrays, same row order).
    """
    test = holdout[holdout[target].notna()]  # censoring: only resolved targets
    scores = np.asarray(score_fn(test, fit_fn(final_train)))  # fit on train only, score the holdout once
    y = test[target].to_numpy()  # resolved labels
    alpha = (1 - confidence) / 2  # two-sided tail
    codes = pd.factorize(test["artist_id"].to_numpy())[0]  # artist id -> 0..n_artists-1
    n_artists = codes.max() + 1  # number of distinct artists
    rng = np.random.default_rng(seed)  # same draws style as the fold bootstrap
    roc_boot = np.empty(n_bootstrap)  # one ROC-AUC per draw
    for i in range(n_bootstrap):
        weights = np.bincount(rng.integers(0, n_artists, n_artists), minlength=n_artists)[codes]  # times each row's artist was drawn
        roc_boot[i] = roc_auc_score(y, scores, sample_weight=weights)  # weighted ROC-AUC, same as resampling artists
    pr_boot = _artist_bootstrap_pr_auc(y, scores, test["artist_id"].to_numpy(), n_bootstrap, seed)  # PR-AUC draws
    by_year = {int(yr): {"rows": int(m.sum()), "positive_rate": float(y[m].mean()), "pr_auc": float(average_precision_score(y[m], scores[m])), "roc_auc": float(roc_auc_score(y[m], scores[m]))}
               for yr in sorted(test["year"].unique()) for m in [(test["year"] == yr).to_numpy()]}  # descriptive, one entry per holdout year
    result = {
        "target": target, "train_rows": len(final_train), "test_rows": len(test), "test_artists": int(n_artists),
        "dropped_unresolved": len(holdout) - len(test), "positive_rate": float(y.mean()),
        "pr_auc": float(average_precision_score(y, scores)), "pr_auc_lo": float(np.nanquantile(pr_boot, alpha)), "pr_auc_hi": float(np.nanquantile(pr_boot, 1 - alpha)),
        "roc_auc": float(roc_auc_score(y, scores)), "roc_auc_lo": float(np.quantile(roc_boot, alpha)), "roc_auc_hi": float(np.quantile(roc_boot, 1 - alpha)),
        "by_year": by_year, "threshold": threshold,
        "classification_report": classification_report(y, (scores >= threshold).astype(int), output_dict=True, target_names=["no new work", "new work"]),
    }
    if return_scores:  # only when asked, so the stored JSON results of the WHEN callers keep their keys
        result["scores"] = scores  # holdout scores, same row order as the labels
        result["labels"] = y  # resolved holdout labels
    return result


def holdout_tables(results_dir) -> dict:
    """Read the saved holdout results into small tables: headline metrics, per-year metrics, precision and recall."""
    import json  # result files are JSON
    from pathlib import Path  # results folder
    headline, by_year, report = [], [], []  # one list per table
    for path in sorted(Path(results_dir).glob("*.json")):  # one file per model and target
        r = json.loads(path.read_text())
        name = path.stem.removesuffix("_" + r["target"])  # model name without the target suffix
        headline.append({"model": name, "target": r["target"], "test_rows": r["test_rows"], "positive_rate": r["positive_rate"],
                         "pr_auc": r["pr_auc"], "pr_auc_lo": r["pr_auc_lo"], "pr_auc_hi": r["pr_auc_hi"],
                         "roc_auc": r["roc_auc"], "roc_auc_lo": r["roc_auc_lo"], "roc_auc_hi": r["roc_auc_hi"]})  # point estimates and intervals
        by_year += [{"model": name, "target": r["target"], "year": y, **v} for y, v in r["by_year"].items()]  # descriptive, per holdout year
        if name == "xgboost_final":  # precision and recall at the threshold are reported for the locked model only
            report += [{"target": r["target"], "class": c, **{k: r["classification_report"][c][k] for k in ("precision", "recall", "f1-score", "support")}} for c in ("no new work", "new work")]
    return {"headline": pd.DataFrame(headline), "by_year": pd.DataFrame(by_year), "report": pd.DataFrame(report)}  # three tables
